// StudioWire — built-in HTTP/WebSocket server (no JUCE dependency).
//
// Job: take audio from the audio thread (lock-free, no allocation), encode it
// (FLAC 16-bit, FLAC 24-bit or Opus, depending on what each listener chose)
// and stream it over WebSocket. The server only listens on 127.0.0.1, so it
// can only be reached from outside through the tunnel. It serves no files from
// disk, only a few built-in pages, and only under /<token>/.

#pragma once

#include "Encoders.h"

#include <array>
#include <atomic>
#include <condition_variable>
#include <cstddef>
#include <cstdint>
#include <map>
#include <memory>
#include <mutex>
#include <string>
#include <thread>
#include <vector>

struct mg_context;
struct mg_connection;

namespace studiowire
{

struct WebAsset
{
    const char* name;          // e.g. "index.html"
    const char* contentType;
    const unsigned char* data;
    std::size_t size;
};

// Provided by WebAssets.cpp (generated by CMake from the web/ folder).
extern const WebAsset kWebAssets[];
extern const std::size_t kNumWebAssets;

class StreamServer
{
public:
    struct Options
    {
        int firstPort = 47800;
        int portAttempts = 20;
        int maxListeners = 5;
        bool dither = true;   // TPDF dither for the 16-bit mode (can be turned off for tests)
        Quality maxQuality = Quality::cd; // stream quality: the cap for listeners
        std::string token;    // empty = random token
    };

    // Audio message format (little-endian):
    //   0..3   'M' 'X' 'S' '2'
    //   4      codec (2 = FLAC, 3 = Opus)
    //   5      channel count
    //   6      bits per sample (16 or 24 for FLAC, 0 for Opus)
    //   7      quality (0 = cd, 1 = hires, 2 = eco)
    //   8..11  stream sample rate (Hz)
    //   12..15 frame count (samples per channel)
    //   16..19 sequence number (per quality)
    //   20..   FLAC: one FLAC frame; Opus: a run of [u16 size][Opus packet]
    static constexpr std::size_t kHeaderSize = 20;
    static constexpr int kChannels = 2;

    StreamServer();
    ~StreamServer();

    bool start (const Options& options, std::string& error);
    void stop();

    bool isRunning() const noexcept            { return running.load(); }
    int getPort() const noexcept               { return port.load(); }
    std::string getToken() const;
    std::string getLocalUrl() const;           // http://127.0.0.1:<port>/<token>/
    std::string getPath() const;               // /<token>/
    int getListenerCount() const noexcept      { return numListeners.load(); }
    int getListenerCount (Quality q) const noexcept { return qualityCount[(std::size_t) q].load(); }
    int getMaxListeners() const noexcept       { return maxListeners; }
    std::uint64_t getBytesSent() const noexcept { return bytesSent.load(); }
    std::uint32_t getSampleRate() const noexcept { return sampleRate.load(); }
    bool isReceivingAudio() const noexcept;
    std::uint64_t getDroppedFrames() const noexcept { return droppedFrames.load(); }
    std::string getEncoderError() const;

    // Stream quality (the cap). Can be changed at any time, from any thread
    // except the audio thread: listeners above it are brought down to the cap
    // and every page is notified.
    void setMaxQuality (Quality q);
    Quality getMaxQuality() const noexcept     { return (Quality) maxQuality.load(); }

    // Called from the audio thread: real-time safe, lock-free.
    void setSampleRate (double sr) noexcept;
    void pushAudio (const float* const* channels, int numChannels, int numFrames) noexcept;

    static std::string randomToken (std::size_t length = 22);

private:
    struct Message
    {
        int opcode;
        std::shared_ptr<const std::vector<std::uint8_t>> data;
    };

    struct Listener
    {
        mg_connection* conn = nullptr;
        Quality quality = Quality::cd;
        std::mutex mutex;
        std::condition_variable cv;
        std::vector<Message> queue;
        std::size_t queuedBytes = 0;
        bool closing = false;
        bool busy = false;   // a batch is being sent
        std::thread writer;
    };

    // civetweb callbacks
    static int  onHttpRequest (mg_connection*, void*);
    static int  onWsConnect (const mg_connection*, void*);
    static void onWsReady (mg_connection*, void*);
    static int  onWsData (mg_connection*, int, char*, std::size_t, void*);
    static void onWsClose (const mg_connection*, void*);

    int handleHttp (mg_connection*);
    void sendResponse (mg_connection*, int status, const char* contentType,
                       const void* body, std::size_t size, bool isHtml);
    std::string infoJson() const;

    void senderLoop();
    void broadcast (int opcode, std::shared_ptr<const std::vector<std::uint8_t>> data, int onlyQuality = -1);
    void enqueue (Listener&, Message msg);
    void writerLoop (Listener*);
    void setEncoderError (const std::string&);
    void waitForWriters (int maxMs);

    mg_context* ctx = nullptr;
    std::string token, wsPath;
    int maxListeners = 5;
    bool dither = true;
    std::atomic<int> maxQuality { (int) Quality::cd };
    std::atomic<int> port { 0 };
    std::atomic<bool> running { false };

    mutable std::mutex listenersMutex;
    std::map<const mg_connection*, std::unique_ptr<Listener>> listeners;
    std::atomic<int> numListeners { 0 };
    std::array<std::atomic<int>, kNumQualities> qualityCount {};

    // SPSC ring buffer (audio thread -> sender thread), interleaved stereo.
    static constexpr std::size_t kRingFrames = 1u << 18;
    std::vector<float> ring;
    std::atomic<std::uint64_t> writePos { 0 }, readPos { 0 };

    std::atomic<std::uint32_t> sampleRate { 48000 };
    std::atomic<std::int64_t> lastPushNs { 0 };
    std::atomic<std::uint64_t> bytesSent { 0 }, droppedFrames { 0 };

    mutable std::mutex errorMutex;
    std::string encoderError;

    std::thread sender;
    std::atomic<bool> quit { false };
};

} // namespace studiowire
